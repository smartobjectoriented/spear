class RealStateIsOffLimits(unittest.TestCase):
    def test_a_test_cannot_open_the_default_store(self):
        with mock.patch.dict(os.environ, {}, clear=False):
            os.environ.pop("SPEAR_KNOWLEDGE_DB", None)
            os.environ.pop("SPEAR_STATE_DIR", None)

            with self.assertRaises(wk.RealStateInTest):
                wk.default_path()

    def test_a_named_state_directory_is_allowed(self):
        directory = tempfile.mkdtemp()

        with mock.patch.dict(os.environ, {"SPEAR_STATE_DIR": directory}):
            os.environ.pop("SPEAR_KNOWLEDGE_DB", None)
            self.assertEqual(wk.default_path(), os.path.join(directory, "knowledge.sqlite3"))

    def test_the_temporary_state_of_a_test_run_does_not_outlive_it(self):
        import subprocess

        program = ("import sys; sys.modules['pytest'] = type(sys)('pytest'); "
                   "from runtime import state_paths; root = state_paths.test_state_root(); "
                   "open(root + '/audit.jsonl', 'w').write('x'); print(root)")
        result = subprocess.run([sys.executable, "-c", program], capture_output=True, text=True,
                                cwd=str(Path(__file__).resolve().parents[1]), check=True)
        root = result.stdout.strip()

        self.assertTrue(root)
        self.assertFalse(os.path.exists(root))


