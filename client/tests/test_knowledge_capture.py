"""One persistent store for what a workspace keeps: workspace knowledge.

/remember records into it; the model's remember tool can only propose; legacy
remembered notes move into it on request, each with no more authority than its
origin earns; and no test ever touches a person's own state. Synthetic data
throughout.
"""

