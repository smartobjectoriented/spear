class Migration(Session):
    def legacy(self):
        path = os.path.join(self.state, "memories-alpha.md")
        store = MarkdownMemoryStore(path, default_scope=MemoryScope.PROJECT)
        store.add("The bootloader lives in boot/uboot.", source=MemorySource.USER)
        store.add("The modem firmware is version 4.", source=MemorySource.AUTHORIZED_TOOL)
        store.add("Always rebuild the image after a kernel change.", source=MemorySource.USER)
        store.add("The last command failed once.", source=MemorySource.USER)
        old = store.add("The display is 320x240.", source=MemorySource.USER)
        store.add("The display is 480x272.", source=MemorySource.USER,
                  supersedes=(old.memory_id,))

        with open(path, "a", encoding="utf-8") as handle:
            handle.write("- [2025-01-02] The radio uses UART3.\n")      # no sidecar entry

        return path

    def migrate(self, path, apply):
        return self.in_("alpha", lambda: knowledge_migration.migrate(
            self.knowledge_commands.knowledge_store(), "alpha", path, apply=apply))

    def test_a_dry_run_counts_and_changes_nothing(self):
        path = self.legacy()
        digest = hashlib.sha256(Path(path).read_bytes()).hexdigest()
        report = self.migrate(path, apply=False)

        self.assertEqual(report["counts"], {
            "user_confirmed": 2, "proposed_model_derived": 1, "imported_unknown": 1,
            "duplicate": 0, "skipped_rule_like": 1, "invalid": 1, "superseded": 1})
        self.assertEqual(self.records("alpha"), [])
        self.assertFalse(os.path.exists(knowledge_migration.marker(path)))
        self.assertEqual(hashlib.sha256(Path(path).read_bytes()).hexdigest(), digest)

    def test_each_note_gets_only_the_authority_its_origin_earns(self):
        path = self.legacy()
        self.migrate(path, apply=True)
        found = {record.statement: (record.lifecycle, record.provenance)
                 for record in self.records("alpha")}

        self.assertEqual(found, {
            "The bootloader lives in boot/uboot.": (wk.Lifecycle.ACTIVE,
                                                    wk.Provenance.USER_CONFIRMED),
            "The display is 480x272.": (wk.Lifecycle.ACTIVE, wk.Provenance.USER_CONFIRMED),
            "The modem firmware is version 4.": (wk.Lifecycle.PROPOSED,
                                                 wk.Provenance.MODEL_DERIVED),
            "The radio uses UART3.": (wk.Lifecycle.PROPOSED, wk.Provenance.IMPORTED)})

    def test_running_it_twice_adds_nothing(self):
        path = self.legacy()
        self.migrate(path, apply=True)
        again = self.migrate(path, apply=True)

        self.assertEqual(len(self.records("alpha")), 4)
        self.assertEqual(again["counts"]["duplicate"], 4)
        self.assertEqual(again["created"], [])

    def test_a_fact_already_known_is_not_recorded_again(self):
        path = self.legacy()
        self.in_("alpha", self.knowledge_commands.remember_fact, "The bootloader lives in boot/uboot.")

        self.assertEqual(self.migrate(path, apply=False)["counts"]["duplicate"], 1)

    def test_the_file_is_kept_and_marked(self):
        path = self.legacy()
        digest = hashlib.sha256(Path(path).read_bytes()).hexdigest()
        self.migrate(path, apply=True)
        marked = json.loads(Path(knowledge_migration.marker(path)).read_text())

        self.assertEqual(hashlib.sha256(Path(path).read_bytes()).hexdigest(), digest)
        self.assertEqual(marked["workspace"], "alpha")

    def test_the_report_never_carries_note_text(self):
        path = self.legacy()
        out = self.in_("alpha", self.knowledge_commands.knowledge_command, "migrate-remember",
                       memories=path)

        self.assertIn("dry run, nothing changed", out)
        self.assertIn("skipped rule like 1", out)

        for text in ("bootloader", "modem", "UART3", "rebuild", "480x272"):
            self.assertNotIn(text, out)

    def test_the_command_applies_only_when_asked(self):
        path = self.legacy()
        self.in_("alpha", self.knowledge_commands.knowledge_command, "migrate-remember", memories=path)
        self.assertEqual(self.records("alpha"), [])

        out = self.in_("alpha", self.knowledge_commands.knowledge_command, "migrate-remember --apply",
                       memories=path)
        self.assertIn("migrated: 7 legacy notes", out)
        self.assertEqual(len(self.records("alpha")), 4)

    def test_the_startup_notice_until_migrated(self):
        path = self.legacy()
        notice = self.in_("alpha", self.knowledge_commands.legacy_notes_notice, memories=path)

        self.assertIn("6 legacy remembered notes are no longer shown to turns", notice)
        self.migrate(path, apply=True)
        self.assertEqual(self.in_("alpha", self.knowledge_commands.legacy_notes_notice, memories=path),
                         "")

    def test_no_note_reaches_another_workspace(self):
        path = self.legacy()
        self.migrate(path, apply=True)

        self.assertEqual(self.records("beta"), [])


